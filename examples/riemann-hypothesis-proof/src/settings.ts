// Per-video settings, read by both the Remotion composition and the Node scripts.
// No browser-only imports here.
import type { Label, Lang } from './types.ts';

export type Settings = {
  /** Narration languages. Each one gets its own timing, since lines differ in length. */
  voices: Lang[];
  /** Burned-in caption languages over the main voice. */
  subtitles: Lang[];
  /** Optional music bed (file under public/), ducked to `volume * duck` while a line plays. */
  music: null | { src: string; volume: number; duck: number };
  /** Intended length of the main cut, in seconds: whatever the story needs (usually 45–90). Lint warns at ±20 %. */
  targetSeconds: number;
  /** Thumbnail frame: scene id + seconds into it. null = a frame from the intro. */
  poster: null | { scene: string; second: number };
  /** YouTube thumbnail (1280x720, from the landscape cut): scene id + seconds. Unset = the poster frame. */
  thumbnail?: null | { scene: string; second: number };
  /** Title of the source article, shown in muted text on the outro card. */
  articleTitle: Label;
  /**
   * Optional author avatar (round, under public/), shown on the outro card. Cameos read their
   * cut-outs from public/avatar/avatar-<pose>.png. null = no avatar.
   */
  avatar?: null | string;
  /** Optional credit, small and muted under the title on the outro card; parts split at " · ". */
  credit?: Label;
};

