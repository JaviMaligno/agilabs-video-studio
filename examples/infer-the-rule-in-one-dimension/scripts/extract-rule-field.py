"""Extract the real geometry and contact landings for the RuleField animation.

Recomputes, read-only, what code-world-models/scripts/region_fit_baseline.py measure_arm does
for the three dose arms (default: seed 10000; arc120 and arc240: the seed whose landing
arc is closest to the arm median): the contact landings inside
the near disc and the algebraic least-squares circle fit on them. Also reads the arm totals
and the two real artifacts quoted on screen.

Run: <cwm>/.venv/bin/python scripts/extract-rule-field.py <path to code-world-models>
Writes: src/data/ruleField.ts (a typed constant, so the pure frame states can import it)
"""
import json
import math
import pathlib
import sys

CWM = pathlib.Path(sys.argv[1]).resolve()
sys.path.insert(0, str(CWM / "src"))
sys.path.insert(0, str(CWM / "scripts"))

from cwm.continuous.envs import PatchField2D            # noqa: E402
from cwm.continuous.contract import collect_transitions  # noqa: E402
from region_fit_baseline import circle_fit, angular_extent, ARMS  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "data" / "ruleField.ts"
SEED = 10_000

base = json.loads((CWM / "results" / "region_fit_baseline.json").read_text())


def pick_seed(label):
    """The arm's seed whose landing arc is closest to the arm median (the article's x axis)."""
    arm = base["dose_arms"][label]
    rows = [r for r in arm["rows"] if "landing_arc_deg" in r]
    return min(rows, key=lambda r: abs(r["landing_arc_deg"] - arm["median_landing_arc_deg"]))["seed"]


doses = []
for label, arc, n_roll in ARMS:
    env = PatchField2D(p1=(3.0, 0.0), p2=(7.0, 0.0), start_arc_deg=arc)
    seed = SEED if label == "default" else pick_seed(label)
    land = []
    for t in collect_transitions(env, n_roll, seed=seed):
        if not t["contact"]:
            continue
        lx, ly = env._integrate(tuple(t["state"]), t["action"])[:2]
        if env._inside(lx, ly, env.p1):
            land.append((round(lx, 4), round(ly, 4)))
    cx, cy, r, _ = circle_fit(land)
    doses.append({"label": label, "seed": seed, "landings": land, "fit": [round(float(cx), 4), round(float(cy), 4), round(float(r), 4)],
                  "arc_deg": round(angular_extent(land, env.p1), 2)})

totals = {k: v["n_recovering_both"] for k, v in base["dose_arms"].items()}
medians = {k: round(v["median_landing_arc_deg"], 1) for k, v in base["dose_arms"].items()}

env = PatchField2D(p1=(3.0, 0.0), p2=(7.0, 0.0))
out = {
    "plane": {"p1": list(env.p1), "p2": list(env.p2), "R": env.R},
    "seed": SEED,
    "doses": doses,
    "lsq_totals": totals,
    "median_arc_deg": medians,
}
OUT.write_text(
    "// Generated by scripts/extract-rule-field.py from code-world-models (read-only). Do not edit.\n"
    "// Seed 10000 (default arm) is the seed of the article's reduction artifact; the two dose arms\n"
    "// use the seed whose landing arc is closest to the arm median (the article's 129 and 185 deg).\n"
    f"export const RULE_FIELD = {json.dumps(out)} as const;\n")
for d in doses:
    print(d["label"], len(d["landings"]), "landings, arc", d["arc_deg"], "fit", d["fit"])
print("totals", totals, "medians", medians)
