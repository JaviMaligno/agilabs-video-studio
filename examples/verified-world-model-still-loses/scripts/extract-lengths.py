"""Write src/data/lengths.ts from code-world-models@origin/main:results/divergence.json.

Usage: python3 scripts/extract-lengths.py [path-to-code-world-models]
CPU only, no model calls. Only the army5x5a game lengths are kept (30 random, 30 competent).
"""
import json
import pathlib
import subprocess
import sys

repo = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "../../../code-world-models").resolve()
raw = subprocess.check_output(["git", "-C", str(repo), "show", "origin/main:results/divergence.json"])
data = json.loads(raw)
army = next(r for r in data["results"] if r["game"] == "army5x5a")
out = pathlib.Path(__file__).resolve().parent.parent / "src" / "data" / "lengths.ts"
out.write_text(
    "// Generated by scripts/extract-lengths.py from code-world-models@origin/main:results/divergence.json\n"
    "// (army5x5a, 30 games per arm, 300 sims). Game lengths in moves; 100 = the move limit.\n"
    f"export const RANDOM_LENGTHS: readonly number[] = {json.dumps(army['random_lengths'])};\n"
    f"export const COMPETENT_LENGTHS: readonly number[] = {json.dumps(army['competent_lengths'])};\n"
    "export const MOVE_LIMIT = 100;\n"
)
print(f"wrote {out}: random {len(army['random_lengths'])}, competent {len(army['competent_lengths'])}")
