test('Jigsaw: neighbouring pieces interlock and borders are flat', () => {
  for (let r = 0; r < jig.N; r++)
    for (let c = 0; c < jig.N; c++) {
      const e = jig.edgesOf(r, c);
      if (r === 0) assert.equal(e[0], 0);
      if (c === jig.N - 1) assert.equal(e[1], 0);
      if (r < jig.N - 1) assert.equal(e[2], -jig.edgesOf(r + 1, c)[0]);
      if (c < jig.N - 1) assert.equal(e[1], -jig.edgesOf(r, c + 1)[3]);
      assert.ok(!jig.piecePath(0, 0, 10, 10, e).includes('NaN'));
    }
});
